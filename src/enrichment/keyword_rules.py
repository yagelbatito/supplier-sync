# Pre-compile: each rule -> (category, regex of alternatives).
_COMPILED = [(cat, re.compile("|".join(re.escape(k) for k in kws))) for cat, kws in _RULES]


def classify_by_rules(name: str, allowed: set) -> str:
    """Return the store category for `name` by keyword rule, or "" if no
    high-confidence rule matches. `allowed` = category names that exist live;
    a rule whose target isn't in `allowed` is skipped (product goes to the LLM)."""
    n = " " + " ".join((name or "").split()) + " "
    for cat, rx in _COMPILED:
        if cat in allowed and rx.search(n):
            return cat
    return ""
